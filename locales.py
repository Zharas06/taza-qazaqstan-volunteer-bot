CATEGORY_KEYS = ["food", "clean", "repair", "emergency"]


def t(lang, key, **kwargs):
    """Возвращает текст по ключу на нужном языке. Если языка нет — русский."""
    lang = lang if lang in TEXTS else "ru"
    text = TEXTS[lang].get(key, TEXTS["ru"].get(key, key))
    if kwargs:
        return text.format(**kwargs)
    return text


def category_name(lang, cat_key):
    """Локализованное название категории."""
    return t(lang, f"cat_{cat_key}")
